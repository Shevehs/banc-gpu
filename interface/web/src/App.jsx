// Configuration read from vLLM: /version, /v1/models, vllm:cache_config_info, the system_fingerprint
// (parallelism, vLLM's default mode) and, if VLLM_SERVER_DEV_MODE=1, /server_info.
const enabled = (v) => (v === true || v === "True" || v === "true" ? "enabled" : v === false || v === "False" || v === "false" ? "disabled" : v ?? "?");
const badMetrics = (s) => s.vllm_lines === 0 || s.metrics_status === "budget" || s.vllm_lines === null || [401, 403, 307, 308].includes(s.metrics_status);
function ServerConfig({ config }) {
  if (config.error) return <p className="error">Configuration not read: {config.error}</p>;
  const servers = config.servers || [];
  const targetModels = (config.target_models || []).map((m) => `${m.id}${m.max_model_len ? ` (max context ${m.max_model_len})` : ""}`).join(", ");
  const fp = config.fingerprint;
  const dec = fp?.decoded;
  const base = (u) => u.replace(/\/metrics$/, "").replace(/\/$/, "");
  const notVllm = !config.given_metrics && servers.every((s) => !s.version && !s.cache_config);
  return (
    <div className="server-config">
      <h4>Server configuration</h4>
      {targetModels && <p>Target models: {targetModels}</p>}
      {fp && (
        <p>Target fingerprint: <code>{fp.raw || "absent"}</code>
          {dec ? ` → TP ${dec.tensor_parallel_size}, PP ${dec.pipeline_parallel_size}, DP ${dec.data_parallel_size}, EP ${dec.enable_expert_parallel ? "yes" : "no"}`
               : fp.raw ? " (unrecognized format: --fingerprint-mode custom?)" : fp.budget_exhausted ? " (not read: time budget exhausted, slow servers)" : fp.response ? "" : " (no response: check the model, key or target)"}
          {dec?.masking_possible && " (or masked if vLLM runs with --fingerprint-mode hash)"}
        </p>
      )}
      {config.deduced_gpus && (
        <p>{config.deduced_gpus.count
          ? `GPUs deduced: ${config.deduced_gpus.explanation}${config.deduced_gpus.masking_possible ? " (1 GPU per server assumed: --fingerprint-mode hash would hide the parallelism)" : ""}`
          : `GPUs not deduced: ${config.deduced_gpus.explanation} (give the GPU count by hand in Results)`}</p>
      )}
      {servers.filter(badMetrics).map((s) => (
        <p key={s.metrics} className="warning">{base(s.metrics)}: {s.vllm_lines === 0 ? "no vllm: metric" : s.metrics_status === "budget" ? "not read (time budget exhausted)"
          : s.vllm_lines == null ? `unreachable${typeof s.metrics_status === "number" ? ` (HTTP ${s.metrics_status})` : ""}` : `HTTP ${s.metrics_status}`}:
          preemptions, cache and KV cache will not be read; give vLLM's own /metrics address.</p>
      ))}
      {notVllm && <p className="warning">The target does not answer like vLLM on /version and /metrics: if it is a gateway (LiteLLM), provide vLLM's /metrics URLs.</p>}
      <table>
        <thead><tr><th>vLLM server</th><th>Version</th><th>Prefix cache</th><th>TP</th><th>PP</th><th>DP</th><th>EP</th>
          <th>Speculative decoding</th><th>max_num_seqs</th><th>max_num_batched_tokens</th></tr></thead>
        <tbody>
          {servers.map((s) => {
            const cf = s.configuration || {};
            // Parallelism: /server_info, otherwise the fingerprint if this server is the target itself.
            const fromFp = !s.configuration && dec && base(s.metrics) === base(config.target) ? dec : null;
            const par = s.configuration ? (cf.parallelism || {}) : fromFp || {};
            const sp = cf.speculative_decoding;
            const sched = cf.scheduler || {};
            const pc = cf.cache?.enable_prefix_caching ?? s.cache_config?.enable_prefix_caching;
            const naPar = s.configuration || fromFp ? "—" : "n/a";
            const na = s.configuration ? "—" : "n/a";
            return (
              <tr key={s.metrics}>
                <td>{base(s.metrics)}</td>
                <td>{s.version || "?"}</td>
                <td>{enabled(pc)}</td>
                <td>{par.tensor_parallel_size ?? naPar}</td>
                <td>{par.pipeline_parallel_size ?? naPar}</td>
                <td>{par.data_parallel_size ?? naPar}</td>
                <td>{s.configuration || fromFp ? enabled(par.enable_expert_parallel) : "n/a"}</td>
                <td>{s.configuration ? (sp ? `${sp.method ?? "?"}, ${sp.num_speculative_tokens ?? "?"} tokens` : "none")
                  : s.speculative_tokens_metrics != null ? (s.speculative_tokens_metrics > 0 ? `${s.speculative_tokens_metrics} tokens` : "none") : "n/a"}</td>
                <td>{sched.max_num_seqs ?? na}</td>
                <td>{sched.max_num_batched_tokens ?? na}</td>
              </tr>
            );
          })}
        </tbody>
      </table>
      <p className="help">Parallelism: read from the system_fingerprint of a one-token completion (vLLM's default mode);
        through a gateway, if it forwards it, it is the fingerprint of the replica that answered. Speculative tokens: counted in /metrics.
        Speculative decoding method and scheduler (n/a): only available through /server_info, if vLLM is started with
        VLLM_SERVER_DEV_MODE=1, a mode that is discouraged because it exposes unauthenticated control endpoints. This reading is redone and
        saved at the start of every run (server_config.json).</p>
    </div>
  );
}

