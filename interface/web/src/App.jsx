// ------------------------------------------------------------------ Runs tab
function Runs({ selection, setSelection }) {
  const [runs, setRuns] = useState([]);
  const [text, setText] = useState("");
  const pos = useRef(0);
  const box = useRef(null);

  useEffect(() => {
    const load = () => api("/api/runs").then(setRuns).catch(() => {});
    load(); const t = setInterval(load, 3000); return () => clearInterval(t);
  }, []);

  useEffect(() => {
    setText(""); pos.current = 0;
    if (!selection) return;
    let done = false;
    const pull = async () => {
      try {
        const r = await api(`/api/runs/${encodeURIComponent(selection)}/log?since=${pos.current}`);
        if (r.text) { pos.current = r.position; setText((t) => (t + r.text).slice(-200000)); }
        if (r.finished && !r.text) done = true;
      } catch { done = true; }
    };
    pull(); const t = setInterval(() => { if (!done) pull(); }, 1500);
    return () => clearInterval(t);
  }, [selection]);

  useEffect(() => { if (box.current) box.current.scrollTop = box.current.scrollHeight; }, [text]);

  const stop = (id) => api(`/api/runs/${encodeURIComponent(id)}/stop`, {
    method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" }).catch((e) => alert(e.message));
  const status = (e) => (e.code === null ? "running" : e.code === 0 ? "finished" : `failed (${e.code})`);

  return (
    <section className="two-columns">
      <div>
        {runs.length === 0 && <p className="note">No run started since the interface was launched.</p>}
        <ul className="list">
          {runs.map((e) => (
            <li key={e.id} className={selection === e.id ? "selected" : ""} onClick={() => setSelection(e.id)}>
              <div><b>{e.label}</b> <span className="badge">{{ agents: "test agents", agentx: "AgentX" }[e.type] || "synthetic"}</span></div>
              <div className="small">{new Date(e.start * 1000).toLocaleTimeString()} · {status(e)}
                {e.code === null && <button className="link" onClick={(ev) => { ev.stopPropagation(); stop(e.id); }}>stop</button>}
              </div>
            </li>
          ))}
        </ul>
      </div>
      <pre className="log" ref={box}>{selection ? text || "…" : "Select a run to see its log."}</pre>
    </section>
  );
}

